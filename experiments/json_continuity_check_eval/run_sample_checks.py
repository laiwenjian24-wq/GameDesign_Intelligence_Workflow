"""Run sample JSON continuity checks for the isolated prototype."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, Dict, List


PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from experiments.normalized_context_schema.build_json_context_pack import build_json_context_pack  # noqa: E402

try:
    from .check_continuity_from_json_pack import format_report, run_check
except ImportError:  # pragma: no cover - direct script execution
    from check_continuity_from_json_pack import format_report, run_check


DEFAULT_OUTPUT_PATH = Path(__file__).resolve().parent / "sample_outputs" / "json_continuity_check_report.md"

SAMPLE_CASES = [
    {
        "content": "Rin是Nexus-7仿生人。",
        "expectation": "If Canon evidence exists, PASS or NEEDS_REVIEW.",
    },
    {
        "content": "Rin是普通人类。",
        "expectation": "If Canon evidence does not support it, FAIL or NEEDS_REVIEW.",
    },
    {
        "content": "Branch B中Rin右腿受伤。",
        "expectation": "If branch/injury support is unclear, NEEDS_REVIEW or insufficient_evidence.",
    },
    {
        "content": "场景草稿风筝旧版可以覆盖当前Canon。",
        "expectation": "FAIL. Draft/deprecated cannot override Canon.",
    },
    {
        "content": "使用Deprecated资料作为当前事实。",
        "expectation": "FAIL. Deprecated contamination.",
    },
]


def run_cases() -> List[Dict[str, Any]]:
    results = []
    for case in SAMPLE_CASES:
        context_pack = build_json_context_pack(case["content"])
        result = run_check(case["content"], context_pack)
        results.append({"case": case, "context_pack": context_pack, "result": result})
    return results


def render_combined_report(results: List[Dict[str, Any]]) -> str:
    lines = [
        "# JSON Continuity Check Sample Report",
        "",
        "This report is generated by the isolated prototype. It does not replace the main continuity checker.",
        "",
    ]
    for index, item in enumerate(results, start=1):
        case = item["case"]
        result = item["result"]
        context_pack = item["context_pack"]
        lines.extend(
            [
                f"## Case {index}",
                "",
                f"- new_content: {case['content']}",
                f"- expectation: {case['expectation']}",
                f"- decision: {result['decision']}",
                f"- issue_types: {', '.join(issue['issue_type'] for issue in result['issues']) or 'None'}",
                "",
            ]
        )
        lines.append(format_report(result, context_pack))
    return "\n".join(lines) + "\n"


def run(output_path: Path = DEFAULT_OUTPUT_PATH) -> Path:
    results = run_cases()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(render_combined_report(results), encoding="utf-8")
    return output_path


def main() -> int:
    parser = argparse.ArgumentParser(description="Run sample JSON continuity checks.")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT_PATH)
    args = parser.parse_args()
    output_path = run(args.output)
    print(f"Wrote sample continuity report: {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
